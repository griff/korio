/// A type that implements `Display` and `Debug`, but not `Value`.
#[derive(Debug)]
struct DisplayDebug;

impl ::std::fmt::Display for DisplayDebug {
    fn fmt(&self, f: &mut ::std::fmt::Formatter<'_>) -> ::std::fmt::Result {
        ::std::write!(f, "Foo")
    }
}

// Tests that macros work across various invocation syntax.
//
// These are quite repetitive, and _could_ be generated by a macro. However,
// they're compile-time tests, so I want to get line numbers etc out of
// failures, and producing them with a macro would muddy the waters a bit.

#[cfg_attr(target_arch = "wasm32", wasm_bindgen_test::wasm_bindgen_test)]
#[test]
fn span() {
    korio_span!(target: "foo_events", Severity::Debug, "foo", bar.baz = ?2, quux = %3, quuux = 4);
    korio_span!(target: "foo_events", Severity::Debug, "foo", bar.baz = 2, quux = 3);
    korio_span!(target: "foo_events", Severity::Debug, "foo", bar.baz = 2, quux = 4,);
    korio_span!(target: "foo_events", Severity::Debug, "foo");
    korio_span!(target: "foo_events", Severity::Debug, "bar",);
    korio_span!(Severity::Debug, "foo", bar.baz = 2, quux = 3);
    korio_span!(Severity::Debug, "foo", bar.baz = 2, quux = 4,);
    korio_span!(Severity::Debug, "foo", bar.baz = 2, quux = 3);
    korio_span!(Severity::Debug, "foo", bar.baz = 2, quux = 4,);
    korio_span!(Severity::Debug, "foo", bar.baz = ?2);
    korio_span!(Severity::Debug, "foo", bar.baz = %2);
    korio_span!(Severity::Debug, "foo");
    korio_span!(Severity::Debug, "bar",);
    korio_span!(
        Severity::Debug,
        "bar",
        foo = display("foo"),
        quux = debug(::std::option::Option::Some(2))
    );
}

