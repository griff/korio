#[cfg_attr(target_arch = "wasm32", wasm_bindgen_test::wasm_bindgen_test)]
#[test]
fn event() {
    korio_event!(Severity::Debug, foo = ?3, bar.baz = %2, quux = false);
    korio_event!(Severity::Debug, foo = 3, bar.baz = 2, quux = false);
    korio_event!(Severity::Debug, foo = 3, bar.baz = 3,);
    korio_event!(Severity::Debug, "foo");
    korio_event!(Severity::Debug, "foo: {}", 3);
    korio_event!(Severity::Info, foo = ?3, bar.baz = %2, quux = false, "hello world {:?}", 42);
    korio_event!(
        Severity::Info,
        foo = 3,
        bar.baz = 2,
        quux = false,
        "hello world {:?}",
        42
    );
    korio_event!(Severity::Info, foo = 3, bar.baz = 3, "hello world {:?}", 42,);
    korio_event!(Severity::Debug, { foo = 3, bar.baz = 80 }, "quux");
    korio_event!(Severity::Debug, { foo = 2, bar.baz = 79 }, "quux {:?}", true);
    korio_event!(Severity::Debug, { foo = 2, bar.baz = 79 }, "quux {:?}, {quux}", true, quux = false);
    korio_event!(Severity::Debug, { foo = ?2, bar.baz = %78 }, "quux");
    korio_event!(target: "foo_events", Severity::Debug, foo = 3, bar.baz = 2, quux = false);
    korio_event!(target: "foo_events", Severity::Debug, foo = 3, bar.baz = 3,);
    //korio_event!(target: "foo_events", Severity::Debug, "foo");
    //korio_event!(target: "foo_events", Severity::Debug, "foo: {}", 3);
    korio_event!(target: "foo_events", Severity::Debug, { foo = 3, bar.baz = 80 }, "quux");
    korio_event!(target: "foo_events", Severity::Debug, { foo = 2, bar.baz = 79 }, "quux {:?}", true);
    korio_event!(target: "foo_events", Severity::Debug, { foo = 2, bar.baz = 79 }, "quux {:?}, {quux}", true, quux = false);
    korio_event!(target: "foo_events", Severity::Debug, { foo = 2, bar.baz = 78, }, "quux");
    let foo = 1;
    korio_event!(Severity::Debug, ?foo);
    korio_event!(Severity::Debug, %foo);
    korio_event!(Severity::Debug, foo);
    korio_event!(
        Severity::Debug,
        foo = display("foo"),
        quux = debug(::std::option::Option::Some(2))
    );
}

